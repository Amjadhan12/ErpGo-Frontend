interface LocaleContextValue {
  language: Language;
  direction: "ltr" | "rtl";
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
}

const LocaleContext = createContext<LocaleContextValue | null>(null);
const LANGUAGE_STORAGE_KEY = "erpgo-language";

function getStoredLanguage(): Language {
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "ps" ? "ps" : "en";
  } catch (error) {
    console.error("Could not read the saved language preference.", error);
    return "en";
  }
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getStoredLanguage);

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch (error) {
      console.error("Could not save the language preference.", error);
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ps" ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo<LocaleContextValue>(
    () => ({
      language,
      direction: language === "ps" ? "rtl" : "ltr",
      setLanguage,
      t: (text) => (language === "ps" ? translations[text] ?? text : text),
    }),
    [language],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const locale = useContext(LocaleContext);
  if (!locale) throw new Error("useLocale must be used inside LocaleProvider.");
  return locale;
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useLocale();

  return (
    <label className="language-switcher">
      <span>{t("Language")}</span>
      <select
        aria-label={t("Language")}
        value={language}
        onChange={(event) => setLanguage(event.currentTarget.value === "ps" ? "ps" : "en")}
      >
        <option value="en">English</option>
        <option value="ps">پښتو</option>
      </select>
    </label>
  );
}
